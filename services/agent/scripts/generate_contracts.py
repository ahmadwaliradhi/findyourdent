"""Generate Pydantic v2 models from the shared JSON Schemas.

Reads every ``packages/contracts/schemas/*.schema.json`` and writes one module per
schema into ``src/findyourdent_agent/contracts/``. The output is deterministic (no
timestamps, stable ordering) and committed.

Usage::

    uv run python scripts/generate_contracts.py          # regenerate
    uv run python scripts/generate_contracts.py --check  # exit 1 if stale (CI)

A ``oneOf`` whose branches are all objects with a ``const`` ``kind`` property is
turned into a Pydantic discriminated union on ``kind`` (the schema files are not
changed; the ``discriminator`` hint is added to an in-memory copy only).
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

SERVICE_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = SERVICE_DIR.parents[1]
SCHEMAS_DIR = REPO_ROOT / "packages" / "contracts" / "schemas"
OUTPUT_DIR = SERVICE_DIR / "src" / "findyourdent_agent" / "contracts"
DISCRIMINATOR_FIELD = "kind"

HEADER = (
    "# Generated by services/agent/scripts/generate_contracts.py from\n"
    "# packages/contracts/schemas/{schema}. Do not edit by hand."
)

CODEGEN_ARGS = [
    "--input-file-type",
    "jsonschema",
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--target-python-version",
    "3.13",
    "--disable-timestamp",
    "--use-title-as-name",
    "--use-annotated",
    "--field-constraints",
    "--use-union-operator",
    "--use-standard-collections",
    "--use-double-quotes",
    "--enum-field-as-literal",
    "all",
    "--collapse-root-models",
    "--use-schema-description",
    "--use-field-description",
    "--keep-model-order",
    "--formatters",
    "ruff-format",
    "ruff-check",
]


def module_name(schema_path: Path) -> str:
    return schema_path.name.removesuffix(".schema.json").replace("-", "_").replace(".", "_")


def _resolve_local(schema: dict[str, Any], ref: str) -> dict[str, Any] | None:
    if not ref.startswith("#/"):
        return None
    node: Any = schema
    for part in ref[2:].split("/"):
        if not isinstance(node, dict) or part not in node:
            return None
        node = node[part]
    return node if isinstance(node, dict) else None


def _kind_const(schema: dict[str, Any], branch: dict[str, Any]) -> str | None:
    target = _resolve_local(schema, branch["$ref"]) if "$ref" in branch else branch
    if not target:
        return None
    kind = target.get("properties", {}).get(DISCRIMINATOR_FIELD, {})
    return kind.get("const") if isinstance(kind, dict) else None


def add_discriminators(schema: dict[str, Any]) -> dict[str, Any]:
    """Annotate oneOf unions that are tagged by a const ``kind`` with a discriminator."""

    def visit(node: Any) -> None:
        if isinstance(node, dict):
            branches = node.get("oneOf")
            if isinstance(branches, list) and branches and "discriminator" not in node:
                kinds = [_kind_const(schema, b) if isinstance(b, dict) else None for b in branches]
                if all(isinstance(k, str) for k in kinds) and len(set(kinds)) == len(kinds):
                    discriminator: dict[str, Any] = {"propertyName": DISCRIMINATOR_FIELD}
                    if all("$ref" in b for b in branches):
                        discriminator["mapping"] = {
                            k: b["$ref"] for k, b in zip(kinds, branches, strict=True)
                        }
                    node["discriminator"] = discriminator
            for value in node.values():
                visit(value)
        elif isinstance(node, list):
            for item in node:
                visit(item)

    visit(schema)
    return schema


def generate_into(out_dir: Path) -> list[str]:
    schemas = sorted(SCHEMAS_DIR.glob("*.schema.json"))
    if not schemas:
        sys.exit(f"No schemas found in {SCHEMAS_DIR}")
    names: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        # Copy every schema so cross-file $refs keep resolving next to each other.
        for schema_path in schemas:
            data = json.loads(schema_path.read_text(encoding="utf-8"))
            (tmp_dir / schema_path.name).write_text(
                json.dumps(add_discriminators(data), indent=2), encoding="utf-8"
            )
        for schema_path in schemas:
            name = module_name(schema_path)
            names.append(name)
            target = out_dir / f"{name}.py"
            subprocess.run(
                [
                    sys.executable,
                    "-m",
                    "datamodel_code_generator",
                    "--input",
                    str(tmp_dir / schema_path.name),
                    "--output",
                    str(target),
                    "--custom-file-header",
                    HEADER.format(schema=schema_path.name),
                    *CODEGEN_ARGS,
                ],
                check=True,
                cwd=out_dir,
                env={**os.environ, "RUFF_CACHE_DIR": str(tmp_dir / ".ruff_cache")},
            )
    init_lines = [
        '"""Pydantic models generated from packages/contracts/schemas. Do not edit by hand."""',
        "",
        *[f"from . import {name}" for name in names],
        "",
        f"__all__ = {json.dumps(names)}",
        "",
    ]
    (out_dir / "__init__.py").write_text("\n".join(init_lines), encoding="utf-8")
    return names


def snapshot(directory: Path) -> dict[str, str]:
    if not directory.exists():
        return {}
    return {p.name: p.read_text(encoding="utf-8") for p in sorted(directory.glob("*.py"))}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        fresh_dir = Path(tmp) / "contracts"
        fresh_dir.mkdir()
        generate_into(fresh_dir)
        fresh = snapshot(fresh_dir)

        if args.check:
            current = snapshot(OUTPUT_DIR)
            if current == fresh:
                print(f"Contracts up to date ({len(fresh)} files).")
                return 0
            for name in sorted(set(current) | set(fresh)):
                if current.get(name) != fresh.get(name):
                    sys.stdout.writelines(
                        difflib.unified_diff(
                            current.get(name, "").splitlines(keepends=True),
                            fresh.get(name, "").splitlines(keepends=True),
                            fromfile=f"committed/{name}",
                            tofile=f"generated/{name}",
                        )
                    )
            print(
                "\nGenerated contracts are stale. Run: "
                "uv run --directory services/agent python scripts/generate_contracts.py",
                file=sys.stderr,
            )
            return 1

        if OUTPUT_DIR.exists():
            shutil.rmtree(OUTPUT_DIR)
        shutil.copytree(fresh_dir, OUTPUT_DIR)
        print(f"Wrote {len(fresh)} files to {OUTPUT_DIR.relative_to(REPO_ROOT)}.")
        return 0


if __name__ == "__main__":
    raise SystemExit(main())
