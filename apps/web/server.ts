// Entry point: `node server.ts` (Node 24 strips the types). Dev uses Vite middleware;
// production (NODE_ENV=production) serves the React Router build.
import { fileURLToPath } from "node:url";
import type { ServerBuild } from "react-router";
import { createApp } from "./server/app.ts";
import { createContextFromEnv } from "./server/context.ts";
import { logger } from "./server/logger.ts";

const port = Number(process.env.PORT ?? 3000);
const production = process.env.NODE_ENV === "production";
const context = createContextFromEnv();

let app: ReturnType<typeof createApp>;
if (production) {
  // @ts-expect-error: generated by `react-router build`
  const build = (await import("./build/server/index.js")) as ServerBuild;
  app = createApp({ mode: "production", build, context: () => context });
} else {
  const { createServer } = await import("vite");
  const root = fileURLToPath(new URL(".", import.meta.url));
  const vite = await createServer({ root, server: { middlewareMode: true }, appType: "custom" });
  app = createApp({ mode: "development", vite, context: () => context });
}

app.listen(port, () => {
  logger.info("web listening", { port, mode: production ? "production" : "development" });
});
